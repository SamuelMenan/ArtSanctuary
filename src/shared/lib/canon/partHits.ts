/** Regiones medidas, por canon → vista. Añadir una vista = trazarla aquí. */
const CANON_PART_HITS: Record<string, Partial<Record<MeasureView, PartHitMap>>> = {
  heroic: { frontal: HEROIC_FRONTAL, posterior: HEROIC_POSTERIOR, lateral: HEROIC_LATERAL },
}

/** Regiones de un canon-vista (vacío si no hay trazado → capa no aparece). */
export function getPartHits(canonId: string, view: MeasureView): PartHitMap {
  return CANON_PART_HITS[canonId]?.[view] ?? {}
}

/** ¿El canon-vista tiene regiones trazadas? */
export function hasPartHits(canonId: string, view: MeasureView): boolean {
  return Object.keys(getPartHits(canonId, view)).length > 0
}

